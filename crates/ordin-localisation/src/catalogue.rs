//! The compiled-in catalogues (Localisation.md Internal Logic A and B1) and the parsed `en-GB`
//! index every check reads.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::sync::OnceLock;

use fluent_syntax::ast::{Entry, Message};
use fluent_syntax::parser;
use fluent_syntax::serializer;
use icu::locale::Locale;

use crate::check::{facts_of, Facts};

// `CATALOGUE_TEXTS`: (tag, concatenated Fluent source), `en-GB` first then alphabetical (build.rs A6);
// `COMPLETE_LOCALES`: the bundled tags whose catalogue holds every `en-GB` identifier (build.rs A4a).
include!(concat!(env!("OUT_DIR"), "/catalogues.rs"));

/// The source and last-resort locale (SA-I18N-00).
pub(crate) const SOURCE_LOCALE: &str = "en-GB";

/// Every locale with a bundled catalogue, `en-GB` first, then alphabetical by tag.
/// Builds with the cargo feature `pseudo-locales` also contain `en-XA` and `ar-XB`.
pub fn bundled_locales() -> &'static [&'static str] {
    static LOCALES: OnceLock<Vec<&'static str>> = OnceLock::new();
    LOCALES.get_or_init(|| CATALOGUE_TEXTS.iter().map(|(tag, _)| *tag).collect())
}

/// The bundled locales whose catalogue holds every `en-GB` message identifier, in
/// `bundled_locales()` order: `en-GB` always, and `en-XA` and `ar-XB` in builds that have them.
// spec: ordin-desktop/components/Localisation#LOC-CMP-1
pub(crate) fn complete_locales() -> &'static [&'static str] {
    COMPLETE_LOCALES
}

/// Every `en-GB` message identifier, sorted; read by the TypeScript-binding generator.
pub fn message_ids() -> &'static [&'static str] {
    crate::id::MESSAGE_IDS
}

/// The compiled-in Fluent source of one bundled locale.
pub(crate) fn bundled_text(tag: &str) -> Option<&'static str> {
    CATALOGUE_TEXTS
        .iter()
        .find(|(candidate, _)| *candidate == tag)
        .map(|(_, text)| *text)
}

/// A pseudo-locale: generated by build.rs, never editable (Error Table, `LOC_LANGUAGE_NOT_EDITABLE`).
pub(crate) fn is_pseudo(tag: &str) -> bool {
    tag == "en-XA" || tag == "ar-XB"
}

/// Parses a BCP 47 tag and returns its canonical spelling (`en-gb` → `en-GB`); at most 35 characters.
pub(crate) fn canonical_tag(raw: &str) -> Option<String> {
    if raw.is_empty() || raw.chars().count() > 35 {
        return None;
    }
    Locale::try_from_str(raw)
        .ok()
        .map(|locale| locale.to_string())
}

/// The `en-GB` message index that `check_entry` and the message listings read.
pub(crate) struct English {
    /// message id → analysed facts.
    pub(crate) facts: HashMap<String, Facts>,
    /// message id → the normalised Fluent source of the entry.
    pub(crate) entries: BTreeMap<String, String>,
    /// `en-GB` term identifiers (without the leading hyphen).
    pub(crate) terms: BTreeSet<String>,
}

pub(crate) fn english() -> &'static English {
    static ENGLISH: OnceLock<English> = OnceLock::new();
    ENGLISH.get_or_init(|| {
        let text = bundled_text(SOURCE_LOCALE).unwrap_or_default();
        let (messages, terms) = entries_of(text);
        let mut facts = HashMap::new();
        let mut entries = BTreeMap::new();
        for (id, message) in &messages {
            facts.insert(id.clone(), facts_of(message));
            entries.insert(id.clone(), render_entry(message));
        }
        English {
            facts,
            entries,
            terms,
        }
    })
}

/// Every message of a Fluent source (comments dropped) and its term identifiers. A source that was
/// accepted by build.rs has no junk.
fn entries_of(text: &str) -> (Vec<(String, Message<String>)>, BTreeSet<String>) {
    let resource = match parser::parse(text.to_string()) {
        Ok(resource) => resource,
        Err((resource, _)) => resource,
    };
    let mut messages = Vec::new();
    let mut terms = BTreeSet::new();
    for entry in resource.body {
        match entry {
            Entry::Message(message) => {
                messages.push((message.id.name.clone(), message));
            }
            Entry::Term(term) => {
                terms.insert(term.id.name);
            }
            _ => {}
        }
    }
    (messages, terms)
}

/// The normalised source of one message: the serialiser's text without its comment and without the
/// final line break.
pub(crate) fn render_entry(message: &Message<String>) -> String {
    let mut message = message.clone();
    message.comment = None;
    let resource = fluent_syntax::ast::Resource {
        body: vec![Entry::Message(message)],
    };
    serializer::serialize(&resource)
        .trim_end_matches('\n')
        .to_string()
}

/// message id → normalised entry, for every message of a source text.
pub(crate) fn entries_by_id(text: &str) -> BTreeMap<String, String> {
    entries_of(text)
        .0
        .iter()
        .map(|(id, message)| (id.clone(), render_entry(message)))
        .collect()
}

/// Parses a reply or file that may hold junk: the messages in it, normalised, in file order. Junk is
/// skipped (LOC-LF-16).
pub(crate) fn messages_in(text: &str) -> Vec<(String, String)> {
    entries_of(text)
        .0
        .iter()
        .map(|(id, message)| (id.clone(), render_entry(message)))
        .collect()
}

/// `text` with each message named in `overrides` replaced by its override (comment kept); an override
/// of a message the text lacks is appended.
pub(crate) fn apply_overrides(text: &str, overrides: &BTreeMap<String, String>) -> String {
    let mut resource = match parser::parse(text.to_string()) {
        Ok(resource) => resource,
        Err((resource, _)) => resource,
    };
    let mut pending: BTreeMap<String, Message<String>> = BTreeMap::new();
    for (id, ftl) in overrides {
        if let Some((_, message)) = entries_of(ftl).0.into_iter().next() {
            pending.insert(id.clone(), message);
        }
    }
    for entry in &mut resource.body {
        if let Entry::Message(message) = entry {
            if let Some(replacement) = pending.remove(&message.id.name) {
                message.value = replacement.value;
                message.attributes = replacement.attributes;
            }
        }
    }
    for (_, message) in pending {
        resource.body.push(Entry::Message(message));
    }
    serializer::serialize(&resource)
}
