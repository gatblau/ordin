//! The TypeScript generator (Internal Logic 15): walks `json_schemas()` and writes the three files
//! the screens module is written against. Output is sorted by name and indented by two spaces, so it
//! is byte-stable.

use std::collections::BTreeSet;

use serde_json::{Map, Value};

use crate::schema::json_schemas;
use crate::wire::ServiceApiVersion;

/// The folder, under the screens module, the files are written to.
pub const OUTPUT_DIR: &str = "src/lib/service-api";
pub const SCHEMA_FILE: &str = "schema.gen.json";
pub const TYPES_FILE: &str = "types.gen.ts";
pub const COMMANDS_FILE: &str = "commands.gen.ts";

const HEADER: &str =
    "// Generated by ordin-service-api-gen from the Service API catalogue. Do not edit.\n";

/// The three generated files, as `(file name, content)`.
pub fn generate() -> Vec<(&'static str, String)> {
    let schema = json_schemas();
    let schema_text = match serde_json::to_string_pretty(&schema) {
        Ok(text) => text + "\n",
        Err(_) => String::new(),
    };
    vec![
        (SCHEMA_FILE, schema_text),
        (TYPES_FILE, types_file(&schema)),
        (COMMANDS_FILE, commands_file(&schema)),
    ]
}

/// A `$defs` name as a TypeScript identifier (`Page<FileEntry>` → `Page_FileEntry`).
pub(crate) fn type_name(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    let mut last_underscore = false;
    for c in raw.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c);
            last_underscore = false;
        } else if !last_underscore && !out.is_empty() {
            out.push('_');
            last_underscore = true;
        }
    }
    while out.ends_with('_') {
        out.pop();
    }
    out
}

/// The name a `$ref` points at.
fn ref_name(reference: &str) -> String {
    type_name(reference.rsplit('/').next().unwrap_or(reference))
}

/// A property key, quoted when it is not a plain identifier.
fn key(name: &str) -> String {
    let plain = name.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    if plain {
        name.to_owned()
    } else {
        serde_json::to_string(name).unwrap_or_default()
    }
}

/// A one-line JSDoc comment for a description, or nothing.
fn doc(schema: &Value, indent: &str) -> String {
    match schema.get("description").and_then(Value::as_str) {
        Some(text) if !text.trim().is_empty() => {
            let one_line = text.split_whitespace().collect::<Vec<_>>().join(" ");
            format!("{indent}/** {} */\n", one_line.replace("*/", "* /"))
        }
        _ => String::new(),
    }
}

/// Wraps a union or intersection in parentheses when it is used inside another expression.
fn grouped(ts: String) -> String {
    let top_level_operator = {
        let mut depth = 0i32;
        let mut found = false;
        for c in ts.chars() {
            match c {
                '{' | '(' | '[' | '<' => depth += 1,
                '}' | ')' | ']' | '>' => depth -= 1,
                '|' | '&' if depth == 0 => found = true,
                _ => {}
            }
        }
        found
    };
    if top_level_operator {
        format!("({ts})")
    } else {
        ts
    }
}

/// Joins alternatives into a union, dropping repeats and keeping the first order.
fn union(parts: Vec<String>) -> String {
    let mut seen = BTreeSet::new();
    let unique: Vec<String> = parts
        .into_iter()
        .filter(|p| seen.insert(p.clone()))
        .collect();
    match unique.len() {
        0 => "never".to_owned(),
        1 => unique.into_iter().next().unwrap_or_default(),
        _ => unique
            .into_iter()
            .map(grouped)
            .collect::<Vec<_>>()
            .join(" | "),
    }
}

/// The TypeScript expression of one schema, at `level` levels of indentation.
pub(crate) fn ts_type(schema: &Value, level: usize) -> String {
    match schema {
        Value::Bool(true) => return "unknown".to_owned(),
        Value::Bool(false) => return "never".to_owned(),
        Value::Object(_) => {}
        _ => return "unknown".to_owned(),
    }
    let mut parts: Vec<String> = Vec::new();
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        parts.push(ref_name(reference));
    }
    if let Some(value) = schema.get("const") {
        parts.push(serde_json::to_string(value).unwrap_or_default());
    }
    if let Some(Value::Array(values)) = schema.get("enum") {
        parts.push(union(
            values
                .iter()
                .map(|v| serde_json::to_string(v).unwrap_or_default())
                .collect(),
        ));
    }
    let body = typed_body(schema, level);
    if let Some(body) = body {
        parts.push(body);
    }
    for combinator in ["oneOf", "anyOf"] {
        if let Some(Value::Array(members)) = schema.get(combinator) {
            parts.push(grouped(union(
                members.iter().map(|m| ts_type(m, level)).collect(),
            )));
        }
    }
    if let Some(Value::Array(members)) = schema.get("allOf") {
        for member in members {
            parts.push(grouped(ts_type(member, level)));
        }
    }
    match parts.len() {
        0 => "unknown".to_owned(),
        1 => parts.into_iter().next().unwrap_or_default(),
        _ => parts
            .into_iter()
            .map(grouped)
            .collect::<Vec<_>>()
            .join(" & "),
    }
}

/// The part of a schema its `type` keyword describes, or `None` when it has none.
fn typed_body(schema: &Value, level: usize) -> Option<String> {
    let types: Vec<&str> = match schema.get("type") {
        Some(Value::String(t)) => vec![t.as_str()],
        Some(Value::Array(ts)) => ts.iter().filter_map(Value::as_str).collect(),
        _ if schema.get("properties").is_some() => vec!["object"],
        _ => return None,
    };
    // A `const` or `enum` already names the value; the type adds nothing.
    if schema.get("const").is_some() || schema.get("enum").is_some() {
        return None;
    }
    let rendered: Vec<String> = types
        .into_iter()
        .map(|t| match t {
            "string" => "string".to_owned(),
            "integer" | "number" => "number".to_owned(),
            "boolean" => "boolean".to_owned(),
            "null" => "null".to_owned(),
            "array" => array_type(schema, level),
            "object" => object_type(schema, level),
            _ => "unknown".to_owned(),
        })
        .collect();
    Some(union(rendered))
}

fn array_type(schema: &Value, level: usize) -> String {
    if let Some(Value::Array(items)) = schema.get("prefixItems") {
        let parts: Vec<String> = items.iter().map(|i| ts_type(i, level)).collect();
        return format!("[{}]", parts.join(", "));
    }
    match schema.get("items") {
        Some(items) => format!("{}[]", grouped(ts_type(items, level))),
        None => "unknown[]".to_owned(),
    }
}

fn object_type(schema: &Value, level: usize) -> String {
    let empty = Map::new();
    let properties = schema
        .get("properties")
        .and_then(Value::as_object)
        .unwrap_or(&empty);
    let required: BTreeSet<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    if properties.is_empty() {
        return match schema.get("additionalProperties") {
            Some(Value::Bool(false)) => "Record<string, never>".to_owned(),
            Some(extra @ Value::Object(_)) => format!("Record<string, {}>", ts_type(extra, level)),
            _ => "Record<string, unknown>".to_owned(),
        };
    }
    let indent = "  ".repeat(level + 1);
    let mut out = String::from("{\n");
    for (name, property) in properties {
        out.push_str(&doc(property, &indent));
        let optional = if required.contains(name.as_str()) {
            ""
        } else {
            "?"
        };
        out.push_str(&format!(
            "{indent}{}{optional}: {};\n",
            key(name),
            ts_type(property, level + 1)
        ));
    }
    out.push_str(&"  ".repeat(level));
    out.push('}');
    out
}

/// True when a `$defs` entry is a plain object type, written as an `interface`.
fn is_plain_object(schema: &Value) -> bool {
    let Some(map) = schema.as_object() else {
        return false;
    };
    let typed_object = map.get("type").and_then(Value::as_str) == Some("object");
    let combined = ["$ref", "oneOf", "anyOf", "allOf", "const", "enum"]
        .iter()
        .any(|k| map.contains_key(*k));
    typed_object
        && !combined
        && map
            .get("properties")
            .and_then(Value::as_object)
            .is_some_and(|p| !p.is_empty())
}

/// `types.gen.ts`: one `export` per `$defs` entry, sorted by name.
fn types_file(schema: &Value) -> String {
    let mut out = String::from(HEADER);
    let empty = Map::new();
    let defs = schema
        .get("$defs")
        .and_then(Value::as_object)
        .unwrap_or(&empty);
    let mut sorted: Vec<(String, &Value)> = defs.iter().map(|(k, v)| (type_name(k), v)).collect();
    sorted.sort_by(|a, b| a.0.cmp(&b.0));
    for (name, def) in sorted {
        out.push('\n');
        out.push_str(&doc(def, ""));
        if is_plain_object(def) {
            out.push_str(&format!(
                "export interface {name} {}\n",
                object_type(def, 0)
            ));
        } else {
            out.push_str(&format!("export type {name} = {};\n", ts_type(def, 0)));
        }
    }
    out
}

/// Every type name a TypeScript expression mentions that the types file exports.
fn names_in(ts: &str, exported: &BTreeSet<String>, into: &mut BTreeSet<String>) {
    let mut word = String::new();
    for c in ts.chars().chain(std::iter::once(' ')) {
        if c.is_ascii_alphanumeric() || c == '_' {
            word.push(c);
        } else {
            if exported.contains(&word) {
                into.insert(word.clone());
            }
            word.clear();
        }
    }
}

/// `commands.gen.ts`: the version, the command map, the IPC names, the event union and `expectNext`.
fn commands_file(schema: &Value) -> String {
    let empty = Map::new();
    let exported: BTreeSet<String> = schema
        .get("$defs")
        .and_then(Value::as_object)
        .unwrap_or(&empty)
        .keys()
        .map(|k| type_name(k))
        .collect();
    let no_commands = Vec::new();
    let commands = schema
        .get("x-ordin-commands")
        .and_then(Value::as_array)
        .unwrap_or(&no_commands);
    let mut rows: Vec<(String, String)> = Vec::new();
    let mut ipc: Vec<(String, String)> = Vec::new();
    let mut imports = BTreeSet::new();
    for command in commands {
        let name = command
            .get("name")
            .and_then(Value::as_str)
            .unwrap_or_default();
        let input = ts_type(command.get("input").unwrap_or(&Value::Bool(true)), 1);
        let result = ts_type(command.get("result").unwrap_or(&Value::Bool(true)), 1);
        names_in(&input, &exported, &mut imports);
        names_in(&result, &exported, &mut imports);
        let scope = command
            .get("scope")
            .and_then(Value::as_str)
            .unwrap_or_default();
        let effect = command
            .get("effect")
            .and_then(Value::as_str)
            .unwrap_or_default();
        rows.push((
            name.to_owned(),
            format!(
                "  {}: {{ input: {input}; result: {result}; scope: \"{scope}\"; effect: \"{effect}\" }};\n",
                serde_json::to_string(name).unwrap_or_default()
            ),
        ));
        ipc.push((
            name.to_owned(),
            command
                .get("ipc_name")
                .and_then(Value::as_str)
                .unwrap_or_default()
                .to_owned(),
        ));
    }
    rows.sort();
    ipc.sort();
    imports.insert("ServiceEvent".to_owned());
    let v = ServiceApiVersion::CURRENT;
    let mut out = String::from(HEADER);
    out.push_str("\nimport type {\n");
    for name in &imports {
        if name == "ServiceEvent" {
            out.push_str("  ServiceEvent as ServiceEventDef,\n");
        } else {
            out.push_str(&format!("  {name},\n"));
        }
    }
    out.push_str("} from \"./types.gen\";\n\n");
    out.push_str(&format!(
        "export const API_VERSION = {{ major: {}, minor: {} }} as const;\n\n",
        v.major, v.minor
    ));
    out.push_str("export type Commands = {\n");
    for (_, row) in &rows {
        out.push_str(row);
    }
    out.push_str("};\n\n");
    out.push_str("export const IPC_NAMES: Record<keyof Commands, string> = {\n");
    for (name, ipc_name) in &ipc {
        out.push_str(&format!(
            "  {}: {},\n",
            serde_json::to_string(name).unwrap_or_default(),
            serde_json::to_string(ipc_name).unwrap_or_default()
        ));
    }
    out.push_str("};\n\n");
    out.push_str("/** Every event, discriminated by `kind`. */\n");
    out.push_str("export type ServiceEvent = ServiceEventDef;\n\n");
    out.push_str(EXPECT_NEXT);
    out
}

/// The gap and order rule of the screens (Internal Logic 9).
const EXPECT_NEXT: &str = r#"/** The last `seq` seen from each backend. */
const lastSeq = new Map<string, number>();

/**
 * The gap and order rule: a `seq` at or below the last one seen from `backend` is late and ignored;
 * one more than the last is next; anything higher is a gap, which the screens log as `SVC_EVENT_GAP`
 * and answer by reloading the affected views by command.
 */
export function expectNext(backend: string, seq: number): "late" | "next" | "gap" {
  const last = lastSeq.get(backend);
  if (last !== undefined && seq <= last) {
    return "late";
  }
  lastSeq.set(backend, seq);
  return last === undefined || seq === last + 1 ? "next" : "gap";
}
"#;

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn names_and_keys() {
        assert_eq!(type_name("Page<FileEntry>"), "Page_FileEntry");
        assert_eq!(type_name("Page_for_FileEntry"), "Page_for_FileEntry");
        assert_eq!(key("a_b"), "a_b");
        assert_eq!(key("x-ordin"), "\"x-ordin\"");
        assert_eq!(grouped("A | B".into()), "(A | B)");
        assert_eq!(grouped("{ a: A | B }".into()), "{ a: A | B }");
        assert_eq!(union(vec![]), "never");
    }

    #[test]
    fn schema_forms() {
        assert_eq!(ts_type(&json!(true), 0), "unknown");
        assert_eq!(ts_type(&json!(false), 0), "never");
        assert_eq!(ts_type(&json!(1), 0), "unknown");
        assert_eq!(ts_type(&json!({}), 0), "unknown");
        assert_eq!(
            ts_type(&json!({"type": ["string", "null"]}), 0),
            "string | null"
        );
        assert_eq!(ts_type(&json!({"type": "integer"}), 0), "number");
        assert_eq!(ts_type(&json!({"type": "boolean"}), 0), "boolean");
        assert_eq!(ts_type(&json!({"type": "x"}), 0), "unknown");
        assert_eq!(ts_type(&json!({"enum": ["a", "b"]}), 0), "\"a\" | \"b\"");
        assert_eq!(
            ts_type(&json!({"type": "string", "const": "a"}), 0),
            "\"a\""
        );
        assert_eq!(
            ts_type(&json!({"type": ["string", "null"], "enum": ["a", null]}), 0),
            "\"a\" | null"
        );
        assert_eq!(
            ts_type(&json!({"type": "array", "items": {"$ref": "#/$defs/A"}}), 0),
            "A[]"
        );
        assert_eq!(ts_type(&json!({"type": "array"}), 0), "unknown[]");
        assert_eq!(
            ts_type(
                &json!({"type": "array", "prefixItems": [{"type": "string"}, {"type": "number"}]}),
                0
            ),
            "[string, number]"
        );
        assert_eq!(
            ts_type(
                &json!({"anyOf": [{"$ref": "#/$defs/A"}, {"type": "null"}]}),
                0
            ),
            "(A | null)"
        );
        assert_eq!(
            ts_type(
                &json!({"type": "object", "additionalProperties": {"type": "string"}}),
                0
            ),
            "Record<string, string>"
        );
        assert_eq!(
            ts_type(&json!({"type": "object", "additionalProperties": false}), 0),
            "Record<string, never>"
        );
        assert_eq!(
            ts_type(&json!({"type": "object"}), 0),
            "Record<string, unknown>"
        );
        assert_eq!(
            ts_type(
                &json!({"allOf": [{"$ref": "#/$defs/A"}, {"$ref": "#/$defs/B"}]}),
                0
            ),
            "A & B"
        );
        let object = json!({
            "type": "object",
            "properties": {"a": {"type": "string", "description": "The a."}, "b": {"type": "integer"}},
            "required": ["a"]
        });
        assert_eq!(
            ts_type(&object, 0),
            "{\n  /** The a. */\n  a: string;\n  b?: number;\n}"
        );
        assert!(is_plain_object(&object));
        assert!(!is_plain_object(
            &json!({"type": "object", "properties": {}})
        ));
        assert!(!is_plain_object(&json!(true)));
    }

    #[test]
    fn expect_next_is_emitted() {
        let mut found = BTreeSet::new();
        let exported: BTreeSet<String> = ["A".to_owned(), "B".to_owned()].into();
        names_in("A[] | { b: B; c: C }", &exported, &mut found);
        assert_eq!(found, exported);
        assert!(EXPECT_NEXT.contains("export function expectNext(backend: string, seq: number)"));
    }
}
